export function RuneSymbol({ runeId, width, height }: { runeId: string; width: number; height: number }) {
  const path = useMemo(() => {
    const builder = Skia.PathBuilder.Make();
    for (const [x1, y1, x2, y2] of runeSegments[runeId] ?? runeSegments.isa) {
      builder.moveTo(x1 * width, y1 * height);
      builder.lineTo(x2 * width, y2 * height);
    }
    return builder.build();
  }, [height, runeId, width]);
  const strokeWidth = Math.max(1.8, Math.min(width, height) * 0.075);

  return (
    <Canvas pointerEvents="none" style={{ width, height }}>
      <Path
        path={path}
        color="rgba(242,161,69,0.26)"
        style="stroke"
        strokeWidth={strokeWidth * 2.15}
        strokeCap="round"
        strokeJoin="round"
      />
      <Path
        path={path}
        color="#C98943"
        style="stroke"
        strokeWidth={strokeWidth}
        strokeCap="round"
        strokeJoin="round"
      />
    </Canvas>
  );
}
